"""cov_summary_lib -- render a repository's committed Verilator coverage
baseline (doc/coverage.md) from the merged coverage databases its
sim/vl/cov.ps1 produced.

Each repository keeps a thin tools/cov_summary.py that declares a `Report`
(title, prose, scope sections, per-file notes, merge groups) and calls
`main(report)`. Everything else lives here: the .dat parser, the per-file
line / branch / toggle aggregation, the uncovered-point list, the table
layout, and the hand-authored "## Hole triage" section that is kept across
regenerations.

Point identity. Verilator records a coverage point once per hierarchy
instance (`h`) and once per module specialization (`page` carries a `__Sz1`
style suffix when a module is elaborated under a second parameter set or a
second bench define). Neither says WHAT is covered, only where it was
collected, so both are dropped from the merge key: a point is covered when
any instance in any bench hit it, and each source point is counted once.

.dat line format (include/verilated_cov.cpp): `C '<name>' <count>`, where
<name> is a run of \\x01<key>\\x02<value> pairs; `t` is the coverage type,
`f` the source path, `l` the line, `o` the comment.

stdlib only, deterministic; the output is always written with LF endings.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Optional, Sequence

METRICS = ("line", "branch", "toggle")
TRIAGE_SENTINEL = "## Hole triage"
INSTANCE_KEYS = frozenset({"h", "page"})

_TRIAGE_DEFAULT = (
    "Classify the uncovered points into: (a) dead-by-design / not reachable "
    "under the elaborated params, (b) covered only by a path this suite does "
    "not drive, (c) REAL gaps → a directed-test follow-up. Inspect "
    "`sim/vl/build/cov/report/annotate_all/` for the per-line `%` (uncovered) / "
    "`+` (covered) annotation, or run `tools/cov_summary.py --holes`.\n"
)


def generated_paragraph(changes: str = "RTL or bench", dat: str = "merged_all.dat") -> str:
    """The standard provenance paragraph under the title."""
    db = "databases" if "*" in dat else "database"
    return (
        "Generated by `tools/cov_summary.py` from the merged Verilator coverage "
        f"{db} (`sim/vl/cov.ps1` → `sim/vl/build/cov/report/{dat}`). "
        "Code coverage only — line / branch / toggle (`--coverage-line "
        "--coverage-toggle`); SV covergroups are unsupported by Verilator. Refresh "
        f"after any {changes} change that intentionally moves coverage.\n"
    )


@dataclass
class Section:
    """One table: the in-scope files whose recorded source path `match`es.

    `title` None renders the table with no `##` heading."""

    title: Optional[str]
    match: Callable[[str], bool]


@dataclass
class LineTable:
    """An extra per-file line-coverage table flagged against a threshold."""

    title: str
    threshold: float = 90.0


@dataclass
class Report:
    repo: Path
    title: str
    body: Sequence[str] = ()
    generated: str = field(default_factory=generated_paragraph)
    sections: Sequence[Section] = ()
    notes: dict = field(default_factory=dict)
    # [(column label, merged .dat basename)], or None to discover every
    # merged_*.dat in the report directory ("all" first, then `group_order`,
    # then the rest sorted).
    groups: Optional[Sequence[tuple]] = (("All", "merged_all.dat"),)
    group_order: Sequence[str] = ()
    # Printed after the collection-tree line when more than one group exists;
    # `{groups}` expands to the labels present.
    groups_line: Optional[str] = None
    total_label: Optional[str] = None
    line_table: Optional[LineTable] = None
    triage_default: str = _TRIAGE_DEFAULT
    # Paths whose uncommitted changes mark the collection tree as dirty.
    dirty_paths: Sequence[str] = ("rtl", "sim")


def is_sv_under(*dirs: str) -> Callable[[str], bool]:
    """Match a `.sv` source recorded under any `/<dir>/` component."""
    needles = tuple(f"/{d.strip('/')}/" for d in dirs)

    def match(path: str) -> bool:
        p = path.replace("\\", "/")
        return p.endswith(".sv") and any(n in p for n in needles)

    return match


def parse_dat(path: Path):
    """-> (agg, holes, fullpaths).

    agg: {basename: {metric: [covered, total]}}; holes: sorted
    [(basename, line, metric, comment)] of uncovered points; fullpaths:
    {basename: first recorded source path}."""
    hits: dict[tuple, list] = {}
    fullpaths: dict[str, str] = {}
    if not path.exists():
        return {}, [], fullpaths
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if not line.startswith("C '"):
                continue
            end = line.rfind("' ")
            if end < 0:
                continue
            name = line[3:end]
            try:
                count = int(line[end + 2:].strip())
            except ValueError:
                continue
            pairs: dict[str, str] = {}
            for fld in name.split("\x01"):
                if not fld:
                    continue
                k, _, v = fld.partition("\x02")
                pairs[k] = v
            fname = pairs.get("f")
            mtype = pairs.get("t")
            if not fname or mtype not in METRICS:
                continue
            base = os.path.basename(fname.replace("\\", "/"))
            fullpaths.setdefault(base, fname)
            key = (base,) + tuple(
                sorted((k, v) for k, v in pairs.items() if k not in INSTANCE_KEYS and k != "f")
            )
            slot = hits.setdefault(key, [mtype, base, 0, pairs])
            slot[2] += count

    agg: dict[str, dict[str, list[int]]] = {}
    holes = []
    for mtype, base, total, pairs in hits.values():
        slot = agg.setdefault(base, {m: [0, 0] for m in METRICS})[mtype]
        slot[1] += 1
        if total > 0:
            slot[0] += 1
        else:
            holes.append((base, int(pairs.get("l", "0") or 0), mtype, pairs.get("o", "")))
    return agg, sorted(holes), fullpaths


def fmt_cell(slot) -> str:
    cov, tot = slot
    if tot == 0:
        return "—"
    return f"{100.0 * cov / tot:4.0f}% ({cov}/{tot})"


def collection_tree(repo: Path, dirty_paths: Sequence[str]) -> str:
    """HEAD, marked when the sources the run measured differ from it."""
    try:
        sha = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=repo, text=True
        ).strip()
        dirty = subprocess.check_output(
            ["git", "status", "--porcelain", "--", *dirty_paths], cwd=repo, text=True
        ).strip()
    except Exception:
        return "`(unknown)`"
    return f"`{sha}` + uncommitted RTL/bench changes" if dirty else f"`{sha}`"


def _discover_groups(report_dir: Path, order: Sequence[str]):
    found = {p.stem[len("merged_"):]: p.name for p in report_dir.glob("merged_*.dat")}
    first = ["all"] + [g for g in order if g != "all"]
    ordered = [g for g in first if g in found]
    ordered += sorted(g for g in found if g not in ordered)
    return [("All" if g == "all" else g.capitalize(), found[g]) for g in ordered]


def render(report: Report, report_dir: Path, out_path: Path):
    """-> (markdown, in-scope files, holes) or raises SystemExit(1)."""
    groups = (
        _discover_groups(report_dir, report.group_order)
        if report.groups is None
        else [g for g in report.groups if (report_dir / g[1]).exists()]
    )
    if not groups:
        sys.stderr.write(
            f"cov_summary: no merged coverage .dat under {report_dir} -- run sim/vl/cov.ps1 first.\n"
        )
        raise SystemExit(1)

    data: dict[str, dict] = {}
    fullpaths: dict[str, str] = {}
    holes_by_group: dict[str, list] = {}
    for label, base in groups:
        agg, holes, paths = parse_dat(report_dir / base)
        data[label] = agg
        holes_by_group[label] = holes
        for k, v in paths.items():
            fullpaths.setdefault(k, v)
    present = [label for label, _ in groups]
    all_files = sorted({f for lbl in present for f in data[lbl]})

    sections = list(report.sections) or [Section(None, lambda _p: True)]
    tables = [(s, [f for f in all_files if s.match(fullpaths.get(f, f))]) for s in sections]
    in_scope = sorted({f for _, files in tables for f in files})
    if not in_scope:
        sys.stderr.write(f"cov_summary: the merged coverage under {report_dir} has no in-scope files.\n")
        raise SystemExit(1)

    multi = len(present) > 1
    with_notes = bool(report.notes)
    empty = {m: [0, 0] for m in METRICS}

    lines = [f"# {report.title}\n", report.generated]
    lines.append(f"- Collection tree: {collection_tree(report.repo, report.dirty_paths)}")
    if multi and report.groups_line:
        lines.append(report.groups_line.format(groups=", ".join(present)))
    lines.extend(report.body)

    for sec, files in tables:
        if not files:
            continue
        if sec.title is not None:
            lines.append(f"## {sec.title}\n")
        hdr = ["File"]
        for lbl in present:
            hdr += [f"{lbl} {m.capitalize()}" if multi else m.capitalize() for m in METRICS]
        if with_notes:
            hdr.append("Note")
        lines.append("| " + " | ".join(hdr) + " |")
        lines.append("|" + "|".join(["---"] * len(hdr)) + "|")
        if report.total_label:
            row = [report.total_label]
            for lbl in present:
                tot = {m: [0, 0] for m in METRICS}
                for f in files:
                    for m in METRICS:
                        s = data[lbl].get(f, empty)[m]
                        tot[m][0] += s[0]
                        tot[m][1] += s[1]
                row += [f"**{fmt_cell(tot[m])}**" for m in METRICS]
            if with_notes:
                row.append("")
            lines.append("| " + " | ".join(row) + " |")
        for f in files:
            row = [f"`{f}`"]
            for lbl in present:
                slots = data[lbl].get(f, empty)
                row += [fmt_cell(slots[m]) for m in METRICS]
            if with_notes:
                row.append(report.notes.get(f, ""))
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

    if report.line_table:
        lt = report.line_table
        lines.append(f"## {lt.title}\n")
        lines.append("| File | Line % | Note |")
        lines.append("|---|---|---|")
        for f in in_scope:
            cov, tot = data[present[0]].get(f, empty)["line"]
            if tot == 0:
                cell = "— n/a"
            else:
                lp = 100.0 * cov / tot
                cell = f"{lp:.0f}% " + ("✅" if lp >= lt.threshold else f"⚠️ below {lt.threshold:.0f}%")
            lines.append(f"| `{f}` | {cell} | {report.notes.get(f, '')} |")
        lines.append("")

    triage = TRIAGE_SENTINEL + "\n\n" + report.triage_default
    if out_path.exists():
        prev = out_path.read_text(encoding="utf-8")
        i = prev.find(TRIAGE_SENTINEL)
        if i >= 0:
            triage = prev[i:].rstrip() + "\n"
    lines.append(triage)

    holes = [h for h in holes_by_group[present[0]] if h[0] in in_scope]
    return "\n".join(lines).rstrip() + "\n", in_scope, holes


def main(report: Report, argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=f"Render {report.title}.")
    ap.add_argument(
        "--report-dir", type=Path, default=report.repo / "sim" / "vl" / "build" / "cov" / "report"
    )
    ap.add_argument("--out", type=Path, default=report.repo / "doc" / "coverage.md")
    ap.add_argument("--holes", action="store_true", help="list uncovered points to stderr")
    args = ap.parse_args(argv)

    try:
        text, files, holes = render(report, args.report_dir, args.out)
    except SystemExit as e:
        return int(e.code or 1)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    sys.stderr.write(f"cov_summary: wrote {args.out} ({len(files)} files)\n")
    if args.holes:
        for base, ln, mtype, comment in holes:
            sys.stderr.write(f"  {base}:{ln} {mtype} {comment}\n")
    return 0
